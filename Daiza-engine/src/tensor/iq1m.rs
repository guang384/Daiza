//! IQ1_M 反量化 (用于 DSpark drafter 的 markov_head_a + log_snr_fc1/fc2)
//!
//! 翻译自 llama.cpp 的 `dequantize_row_iq1_m`。每个 block 56 字节,承载 256 个权重
//! (1.75 bits/weight)。算法:
//!
//! - `scales[8]` 当作 4 个 u16;每个 u16 高 4 bit 贡献给全局 d (拼成 f16),低 12 bit
//!   承载 4 个 3-bit 子 scale。
//! - 每个 sub-block (32 权重) 用 4 个 11-bit grid 索引查 `IQ1S_GRID` (u64 → 8 个 i8),
//!   再叠加 ±0.125 的 delta,乘以 `d * (2*sc + 1)`。
//!
//! 参考: ggml-common.h `block_iq1_m`, ggml-quants.c `dequantize_row_iq1_m`。

