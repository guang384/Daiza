/// 把 IQ1_M 的 raw bytes 反量化为 F32 vec
///
/// - `data`: 完整张量的字节 (IQ1_M 编码)
/// - `n_elements`: 权重元素总数 (必须为 256 的倍数; 末尾不足补零, 本引擎假设齐整)
///
/// 返回长度为 `n_elements` 的 F32 向量
pub fn dequantize_iq1m(data: &[u8], n_elements: usize) -> Vec<f32> {
    let n_blocks = n_elements.div_ceil(IQ1M_GROUP_SIZE);
    let mut out = Vec::with_capacity(n_elements);
    for b in 0..n_blocks {
        let bs = b * IQ1M_BLOCK_BYTES;
        if bs + IQ1M_BLOCK_BYTES > data.len() {
            break;
        }
        let block = &data[bs..bs + IQ1M_BLOCK_BYTES];
        dequantize_block_into(block, &mut out);
        if out.len() >= n_elements {
            out.truncate(n_elements);
            return out;
        }
    }
    while out.len() < n_elements {
        out.push(0.0);
    }
    out
}

/// 反量化 IQ1_M 单行, 写入 caller 提供的 slice (用于 matvec, 避免分配)
///
/// - `data`: 整个 IQ1_M 张量的字节
/// - `row_idx`: 第几行 (0-based)
/// - `n_cols`: 权重列数 (输入维度, 必须为 256 的倍数)
/// - `out`: 输出缓冲, 长度必须 >= n_cols
pub fn dequantize_iq1m_row_into(data: &[u8], row_idx: usize, n_cols: usize, out: &mut [f32]) {
    debug_assert!(out.len() >= n_cols);
    let blocks_per_row = n_cols.div_ceil(IQ1M_GROUP_SIZE);
    let row_byte_offset = row_idx * (blocks_per_row * IQ1M_BLOCK_BYTES);
    if row_byte_offset > data.len() {
        for v in out[..n_cols].iter_mut() {
            *v = 0.0;
        }
        return;
    }
    let row_bytes = &data[row_byte_offset..];
    let mut out_idx = 0;
    for b in 0..blocks_per_row {
        let bs = b * IQ1M_BLOCK_BYTES;
        if bs + IQ1M_BLOCK_BYTES > row_bytes.len() {
            break;
        }
        let block = &row_bytes[bs..bs + IQ1M_BLOCK_BYTES];
        dequantize_block_into_checked(block, out, &mut out_idx, n_cols);
        if out_idx >= n_cols {
            return;
        }
    }
    while out_idx < n_cols {
        out[out_idx] = 0.0;
        out_idx += 1;
    }
}

/// IQ1_M matvec 标量实现: y[i] = dot(W_row_i, x)
///
/// 与 `dequantize_iq1m_row_into` + 手动 dot 等价, 但避免中间 Vec 分配。
pub fn dot_iq1m_row_scalar(data: &[u8], row_idx: usize, n_cols: usize, x: &[f32]) -> f32 {
    debug_assert!(x.len() >= n_cols);
    let blocks_per_row = n_cols.div_ceil(IQ1M_GROUP_SIZE);
    let row_byte_offset = row_idx * (blocks_per_row * IQ1M_BLOCK_BYTES);
    if row_byte_offset > data.len() {
        return 0.0;
    }
    let row_bytes = &data[row_byte_offset..];

    let mut acc = 0.0f32;
    let mut w_buf = [0.0f32; 256];
    for b in 0..blocks_per_row {
        let bs = b * IQ1M_BLOCK_BYTES;
        if bs + IQ1M_BLOCK_BYTES > row_bytes.len() {
            break;
        }
        let block = &row_bytes[bs..bs + IQ1M_BLOCK_BYTES];
        let mut n_written = 0usize;
        dequantize_block_into_checked(block, &mut w_buf, &mut n_written, 256);
        let x_off = b * IQ1M_GROUP_SIZE;
        let mut group_acc = 0.0f32;
        for j in 0..n_written {
            if x_off + j >= n_cols {
                break;
            }
            group_acc += w_buf[j] * x[x_off + j];
        }
        acc += group_acc;
    }
    acc
}

